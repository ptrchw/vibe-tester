function generateHistory(basePrice: number, points: number = 30, volatility: number = 0.015) {
  const result = [];
  let currentPrice = basePrice * 0.96;
  const now = new Date();
  
  for (let i = points; i >= 0; i--) {
    const time = new Date(now.getTime() - i * 3600 * 1000 * 4);
    const changePercent = (Math.random() - 0.48) * volatility;
    currentPrice = currentPrice * (1 + changePercent);
    result.push({
      time: time.toLocaleTimeString([], { hour: '2-digit', minute: '2-digit' }),
      price: Number(currentPrice.toFixed(2))
    });
  }
  return result;
}

